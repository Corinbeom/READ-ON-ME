CREATE TABLE recommendation_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id UUID NOT NULL UNIQUE,
    query TEXT NOT NULL,
    outcome VARCHAR(24) NOT NULL,
    books JSONB NOT NULL CHECK (jsonb_typeof(books) = 'array'),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(500),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A submitted evaluation remains available after the search job's regular expiry.
CREATE INDEX idx_recommendation_feedback_rating ON recommendation_feedback (rating, id DESC);
